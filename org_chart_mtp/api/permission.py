import frappe


def has_app_permission() -> bool:
	"""Доступ к карточке приложения на домашнем экране Desk.

	Оргчарт доступен всем вошедшим пользователям Desk: структура компании
	и контакты — публичная информация; чувствительные данные (цели,
	метрики) фильтруются сервером по скоупам внутри get_org_data.
	"""
	return frappe.session.user not in ("Guest", None)
